#pragma once

namespace ZFC
{
	//=============================================================================
	//
	// Synopsis:    Point;
	//                - 범용으로 사용하는 정수형 2차원 좌표 값 타입.
	//                - Windows 등 특정 플랫폼 타입에 의존하지 않는다.
	//                - 맵 좌표와 맵 크기 표현에 사용한다.
	//                - Core 계층이 제공하며 플랫폼을 알지 못한다.
	//
	//=============================================================================
	struct Point
	{
		int x;   // 가로 좌표(열)
		int y;   // 세로 좌표(행)
	};
}
