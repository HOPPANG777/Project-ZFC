#pragma once

//========================================
// System Includes
//========================================
#include <vector>

//========================================
// Project Includes
//========================================
#include "TileType.h"

namespace ZFC
{
	//=============================================================================
	//
	// Synopsis:    TileRow / TileGrid;
	//                - 타일 맵을 표현하기 위한 std::vector 기반 타입 별칭.
	//                - TileRow 는 타일 한 줄(행), TileGrid 는 그 행들의 모음이다.
	//                - [y][x](행, 열) 순으로 접근하는 2차원 구조를 의도한다.
	//
	//=============================================================================

	// 타일 한 줄(행). 가로 방향으로 늘어선 타일들의 모음이다.
	using TileRow = std::vector<TileType>;
	// 타일 그리드. 행(TileRow)들을 세로로 쌓은 2차원 타일 맵이다.
	using TileGrid = std::vector<TileRow>;
}
